  function isItalic(style) {
    return String(style === undefined || style === null ? 'normal' : style)
      .toLowerCase() === 'italic';
  }

  /* Face resolution. Only three faces are vendored, so an italic request resolves to the
   * 400 italic table at any weight -- the badge spec only ever asks for italic at 400. */
  function tableFor(weight, style) {
    if (isItalic(style)) return ADV_ITALIC;
    return (Number(weight) >= 700) ? ADV_BOLD : ADV_REGULAR;
  }

  function notdefFor(weight, style) {
    if (isItalic(style)) return NOTDEF_ITALIC;
    return (Number(weight) >= 700) ? NOTDEF_BOLD : NOTDEF_REGULAR;
  }

  // Shared guard: a non-numeric or non-finite size must never leak a NaN into a layout.
  // The spec computes baseline = lineTop + ascentPt(size), so one NaN silently wrecks a
  // whole badge; 0 is the safe, visible-as-wrong answer.
  function safeSize(sizePt) {
    var n = Number(sizePt);
    return isFinite(n) ? n : 0;
  }

  /**
   * Sum of advance widths for \`text\` at \`sizePt\`, in points. No kerning.
   * @param {string} text
   * @param {number} sizePt
   * @param {number} weight  400 or 700
   * @param {string} [style] 'normal' (default) or 'italic'
   * Pure and synchronous. Returns 0 for null/empty text or a non-finite size.
   */
  function widthOf(text, sizePt, weight, style) {
    if (text === null || text === undefined) return 0;
    var s = String(text);
    if (s.length === 0) return 0;
    var size = safeSize(sizePt);
    if (size === 0) return 0;
    var t = tableFor(weight, style);
    var fallback = notdefFor(weight, style);
    var units = 0;
    var i = 0;
    while (i < s.length) {
      var cp = s.charCodeAt(i);
      var step = 1;
      // combine surrogate pairs so astral codepoints are looked up correctly
      if (cp >= 0xD800 && cp <= 0xDBFF && i + 1 < s.length) {
        var lo = s.charCodeAt(i + 1);
        if (lo >= 0xDC00 && lo <= 0xDFFF) {
          cp = (cp - 0xD800) * 0x400 + (lo - 0xDC00) + 0x10000;
          step = 2;
        }
      }
      var a = t[cp];
      units += (a === undefined ? fallback : a);
      i += step;
    }
    return units * size / UPEM;
  }

  /** hhea ascent at sizePt, in points. Returns 0 for a non-finite size. */
  function ascentPt(sizePt) { return ASCENT / UPEM * safeSize(sizePt); }

  /** abs(hhea descent) at sizePt, in points. Returns 0 for a non-finite size. */
  function descentPt(sizePt) { return DESCENT / UPEM * safeSize(sizePt); }

  /** Cap height at sizePt, in points. Returns 0 for a non-finite size.
   *  Optical centering uses this for the top of the ink box:
   *    inkTop = firstBaseline - capHeightPt(sizeOfFirstLine) */
  function capHeightPt(sizePt) { return CAP_HEIGHT / UPEM * safeSize(sizePt); }

  /** Real lowercase descender depth at sizePt, in points (positive). Returns 0 for a
   *  non-finite size. Optical centering uses this for the bottom of the ink box:
   *    inkBottom = lastBaseline + descenderDepthPt(sizeOfLastLine) */
  function descenderDepthPt(sizePt) { return DESCENDER_DEPTH / UPEM * safeSize(sizePt); }

